"""Discovery scoreboard: every number is computed from data/interim outputs, nothing typed by hand."""

import csv
import json
from collections import Counter
from pathlib import Path

from research.regnum import REGIONS

ROOT = Path(__file__).resolve().parents[1]
INTERIM = ROOT / "data" / "interim"
OUT = ROOT / "research" / "scoreboard.md"
# Later files supersede earlier ones for the same year (the Q3 file must not beat the full-year file).
STATSUD_PRIORITY = ["adm-decision-2025-9.xlsx", "adm-decision-2025-12.xlsx", "adm-2026-6.xlsx"]


def rows(name: str) -> list[dict]:
    with open(INTERIM / name, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def pct(a: int, b: int) -> str:
    return f"{a:,}/{b:,} = {a / b:.1%}" if b else f"{a}/0"


def court_rates() -> list[tuple[str, int, int]]:
    best: dict[str, tuple[int, dict]] = {}
    for r in rows("statsud_rates.csv"):
        if r["body_type"] != "hokimlik" or r["region"] != "JAMI":
            continue
        rank = STATSUD_PRIORITY.index(r["source"]) if r["source"] in STATSUD_PRIORITY else -1
        if r["year"] not in best or rank > best[r["year"]][0]:
            best[r["year"]] = (rank, r)
    return [(y, int(best[y][1]["heard"]), int(best[y][1]["satisfied"])) for y in sorted(best)]


def body_label(code: str) -> str:
    region, district, _ = (code.split("-") + ["", "", ""])[:3]
    return f"{REGIONS.get(int(region), region)} district {district}" if region.isdigit() else code


def main() -> None:
    e = rows("eqaror_stages.csv")
    tracked = [r for r in e if r["discussion_done"] in ("0", "1")]
    norm = [r for r in tracked if r["is_normative"] == "1"]
    passed = rows("adliya_passed_but_invalid.csv")
    asos = Counter(r["asos_kind"] or "blank" for r in e)
    design = rows("case_designcode_eqaror.csv")

    w = rows("regulation_window.csv")
    open_ = [r for r in w if r["is_open"] == "True"]
    closed = [r for r in w if r["is_open"] == "False"]
    open_flags = sum(r["eif_class"] == "before_end" for r in open_)
    closed_flags = sum(r["eif_class"] == "before_end" for r in closed)
    gaps = sum(bool(r["clause_gap"]) for r in w)

    dup = rows("duplicate_flags.csv")
    docs = json.loads((INTERIM / "district_docs.json").read_text(encoding="utf-8"))
    bodies = {d["body_name"] for d in docs}
    dup_bodies = ", ".join(sorted({body_label(r["body"]) for r in dup}))
    labels = Counter(r["label"] for r in rows("cancellation_labels.csv"))
    orig = rows("positive_originals.csv")
    resolved = sum(r["resolved"] in ("True", "1", "yes") for r in orig)

    court = court_rates()
    heard, invalid = sum(h for _, h, _ in court), sum(s for _, _, s in court)
    disc_skip = sum(r["discussion_done"] == "0" for r in norm)
    exp_skip = sum(r["expertise_done"] == "0" for r in norm)

    a1 = (
        f"| A1 | Skipped stage (E-qaror) | {len(e)} declared invalid ({len(tracked)} with a tracker) "
        f"| normative only: discussion skipped {pct(disc_skip, len(norm))}, expertise skipped {pct(exp_skip, len(norm))} "
        "| not measured: E-qaror throttled the control set | pending | strong cases, no number yet |"
    )
    a2 = (
        f"| A2 | Enters into force before discussion ends | {len(open_)} open + {len(closed)} closed local drafts "
        f"| open {pct(open_flags, len(open_))}, closed {pct(closed_flags, len(closed))} | n/a | pending "
        "| rare; 2 live demo drafts |"
    )
    a3 = (
        f"| A3 | Duplicate / double repeal (lex.uz) | {len(docs)} decisions from {len(bodies)} bodies "
        f"| {len(dup)} flags, all in {dup_bodies} | n/a | pending | high precision, small reach |"
    )
    lines = [
        "# Discovery scoreboard",
        "",
        "Generated by `research/scoreboard.py` from `data/interim/`. Lawyer precision: 0 flags reviewed yet.",
        "",
        "## Official base rate (stat.sud.uz: claims to declare a hokimlik decision invalid; counts claims, not decisions)",
        "",
        "| Year | Claims heard | Claims satisfied |",
        "|---|---|---|",
        *[f"| {y} | {h:,} | {pct(s, h)} |" for y, h, s in court],
        f"| **All** | **{heard:,}** | **{pct(invalid, heard)}** |",
        "",
        "## Patterns",
        "",
        "| # | Pattern | N scanned | N flagged | Lift vs control | Lawyer precision | Verdict |",
        "|---|---|---|---|---|---|---|",
        a1,
        a2,
        a3,
        "",
        "## Side findings",
        "",
        f"- Who triggered the {len(e)} E-qaror invalidations: {', '.join(f'{k} {v}' for k, v in asos.most_common())}.",
        f"- Declared invalid although legal expertise is green on E-qaror: {pct(len(passed), len(tracked))}.",
        f"- Drafts with a clause-numbering gap: {pct(gaps, len(w))}.",
        f"- lex.uz cancellation labels: {', '.join(f'{k} {v}' for k, v in labels.most_common())}; "
        + f"originals resolved {pct(resolved, len(orig))}.",
    ]
    lines += [
        f"- Design-code {d['reg_number']} ({d['date']}): {d['status']}; public discussion done = {d['discussion_done']}, "
        f"legal expertise done = {d['expertise_done']}."
        for d in design
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
